/** \file main.cpp
 * fg-configurator: save the default metadata of the feeLLGood output files (author,
 * affiliation, licence) to $XDG_CONFIG_HOME/feellgood/default.yml, with a dialog window or,
 * without display, in text mode.
 */

#include <cstdlib>
#include <iostream>
#include <stdexcept>
#include <string>

#include <QApplication>
#include <QCloseEvent>
#include <QComboBox>
#include <QCommandLineParser>
#include <QDir>
#include <QFile>
#include <QGridLayout>
#include <QHBoxLayout>
#include <QLabel>
#include <QLineEdit>
#include <QMessageBox>
#include <QPushButton>
#include <QTextStream>
#include <QWidget>

namespace
    {
const QStringList licences = {"None", "CC BY", "CC BY-SA"};
const QString configFileName = "default.yml";

/** Metadata written to the configuration file. */
struct Metadata
    {
    QString author;
    QString affiliation;
    QString licence;
    };

/** Write the metadata to the configuration file, $XDG_CONFIG_HOME/feellgood/default.yml
 * ($XDG_CONFIG_HOME defaults to ~/.config), creating the directory if needed. Empty fields
 * and the "None" licence are left out. Returns a message giving the path of the file. Throws
 * std::runtime_error if the directory cannot be created or the file cannot be written. */
QString writeYaml(const Metadata &md)
    {
    const char *xdg = std::getenv("XDG_CONFIG_HOME");
    const QString configDir = (xdg != nullptr && *xdg != '\0')
                                      ? QString::fromLocal8Bit(xdg)
                                      : QDir::homePath() + "/.config";
    const QString path = configDir + "/feellgood";
    if (!QDir().mkpath(path))
        {
        throw std::runtime_error("not authorized to create " + path.toStdString());
        }
    const QString outputFile = path + "/" + configFileName;
    QFile file(outputFile);
    if (!file.open(QIODevice::WriteOnly | QIODevice::Text | QIODevice::Truncate))
        {
        throw std::runtime_error("cannot write " + outputFile.toStdString());
        }
    QTextStream out(&file);
    out.setCodec("UTF-8");
    out << "# feeLLGood default parameters\n"
           "# This file was generated by feellgood configurator\n"
           "\n"
           "outputs:\n"
           "  metadata:\n";
    if (!md.author.isEmpty())
        {
        out << "    Author: " << md.author << "\n";
        }
    if (!md.affiliation.isEmpty())
        {
        out << "    Affiliation: " << md.affiliation << "\n";
        }
    if (md.licence != "None")
        {
        out << "    Licence: " << md.licence << "\n";
        }
    return outputFile + " written.";
    }

/** \class MainWindow
 * Dialog window with the author, affiliation and licence fields, and Cancel, Save and Ok
 * buttons. A '*' in the title marks unsaved changes.
 */
class MainWindow : public QWidget
    {
public:
    /** Build and show the window. */
    MainWindow()
        {
        resize(400, 200);
        setWindowTitle("feeLLGood config");
        auto *layout = new QGridLayout(this);

        layout->addWidget(new QLabel("Username:"), 0, 0);
        userNameLineEdit = new QLineEdit;
        connect(userNameLineEdit, &QLineEdit::textChanged, this, &MainWindow::markModified);
        layout->addWidget(userNameLineEdit, 0, 1, 1, 2);

        layout->addWidget(new QLabel("Affiliation:"), 1, 0);
        affiliationLineEdit = new QLineEdit;
        connect(affiliationLineEdit, &QLineEdit::textChanged, this, &MainWindow::markModified);
        layout->addWidget(affiliationLineEdit, 1, 1, 1, 2);

        layout->addWidget(new QLabel("Licence:"), 2, 0);
        licenceComboBox = new QComboBox;
        licenceComboBox->setToolTip("Licence of the output file(s).");
        licenceComboBox->addItems(licences);
        connect(licenceComboBox, &QComboBox::currentTextChanged, this,
                &MainWindow::markModified);
        layout->addWidget(licenceComboBox, 2, 1, 1, 2);

        echoText = new QLabel("");
        layout->addWidget(echoText, 4, 0, 1, 3);

        auto *cancelBtn = new QPushButton("Cancel");
        cancelBtn->setToolTip("Quit without saving.");
        connect(cancelBtn, &QPushButton::clicked, this, &QWidget::close);
        auto *saveBtn = new QPushButton("Save");
        saveBtn->setToolTip("Save config to a yaml file.\n"
                            "If a config file already exists it is overwritten.");
        connect(saveBtn, &QPushButton::clicked, this, &MainWindow::writeConfig);
        auto *okBtn = new QPushButton("Ok");
        okBtn->setToolTip("Save and Quit");
        connect(okBtn, &QPushButton::clicked, this, &MainWindow::saveAndClose);
        auto *hLayout = new QHBoxLayout;
        hLayout->addWidget(cancelBtn);
        hLayout->addWidget(saveBtn);
        hLayout->addWidget(okBtn);
        layout->addLayout(hLayout, 3, 0, 1, 3);
        show();
        }

protected:
    /** Ask for confirmation before closing, unless Ok was clicked. */
    void closeEvent(QCloseEvent *event) override
        {
        if (quitting
            || QMessageBox::question(this, "QUIT", "Are you sure want to quit?",
                                     QMessageBox::Yes | QMessageBox::No)
                       == QMessageBox::Yes)
            {
            event->accept();
            }
        else
            {
            event->ignore();
            }
        }

private:
    /** Save the configuration, then quit. The window stays open if saving failed. */
    void saveAndClose()
        {
        if (writeConfig())
            {
            std::cout << "config done.\n";
            quitting = true;
            close();
            }
        }

    /** Write the configuration file, show the result in the window and return true on
     * success. */
    bool writeConfig()
        {
        const Metadata md = {userNameLineEdit->text(), affiliationLineEdit->text(),
                             licenceComboBox->currentText()};
        try
            {
            echoText->setText(writeYaml(md));
            setWindowTitle(" feeLLGood config");
            return true;
            }
        catch (const std::exception &e)
            {
            echoText->setText(QString::fromStdString(e.what()));
            QMessageBox::critical(this, "Error", QString::fromStdString(e.what()));
            return false;
            }
        }

    /** Mark the configuration as modified: '*' in the title, no message. */
    void markModified()
        {
        setWindowTitle("*feeLLGood config");
        echoText->setText("");
        }

    QLineEdit *userNameLineEdit;
    QLineEdit *affiliationLineEdit;
    QComboBox *licenceComboBox;
    QLabel *echoText;
    bool quitting = false;  //!< true once Ok saved the configuration
    };

/** Read a line from the standard input after printing prompt. */
QString prompt(const std::string &prompt)
    {
    std::cout << prompt << std::flush;
    std::string line;
    std::getline(std::cin, line);
    return QString::fromStdString(line);
    }

/** Text mode: ask for the metadata on the terminal and write the configuration file. An
 * invalid licence choice selects "None". In verbose mode, print the configuration. Returns 1
 * if the file cannot be written. */
int dialog(bool verbose)
    {
    std::cout << "This is feellgood configurator, to ease metadata handling.\n";
    Metadata md;
    md.author = prompt("Author: ");
    md.affiliation = prompt("Affiliation: ");
    std::cout << "Licence:\n";
    for (int i = 0; i < licences.size(); ++i)
        {
        std::cout << " " << i << " - " << licences[i].toStdString() << '\n';
        }
    bool ok;
    int idx = prompt("Licence choice (0-" + std::to_string(licences.size() - 1) + "): ")
                      .trimmed()
                      .toInt(&ok);
    if (!ok || idx < 0 || idx >= licences.size())
        {
        idx = 0;
        }
    md.licence = licences[idx];
    try
        {
        const QString message = writeYaml(md);
        if (verbose)
            {
            std::cout << "config= {'Author': '" << md.author.toStdString()
                      << "', 'Affiliation': '" << md.affiliation.toStdString()
                      << "', 'Licence': '" << md.licence.toStdString() << "'}\n"
                      << message.toStdString() << '\n';
            }
        }
    catch (const std::exception &e)
        {
        std::cerr << e.what() << '\n';
        return 1;
        }
    return 0;
    }

/** True if a graphical display is available: DISPLAY is set (Qt 5 uses X11 by default), or
 * QT_QPA_PLATFORM selects a platform explicitly. Always true on Windows. */
bool hasDisplay()
    {
#ifdef _WIN32
    return true;
#else
    const char *display = std::getenv("DISPLAY");
    const char *platform = std::getenv("QT_QPA_PLATFORM");
    return (display != nullptr && *display != '\0') || (platform != nullptr && *platform != '\0');
#endif
    }

/** Parse the command line options into parser for app. Prints the version and exits if
 * --version is given. --version has no short form, since -v is --verbose. */
void parseCommandLine(QCommandLineParser &parser, const QCoreApplication &app)
    {
    parser.setApplicationDescription("save configuration for feeLLGood\n\n"
                                     "Define author and affiliation, licence.");
    parser.addHelpOption();
    parser.addOption({"version", "show the version number"});
    parser.addOption({{"v", "verbose"}, "verbose mode, print all inputs"});
    parser.process(app);
    if (parser.isSet("version"))
        {
        std::cout << "fg-configurator " << FG_VERSION << '\n';
        std::exit(0);
        }
    }
    }  // namespace

/** Show the dialog window if there is a display, otherwise ask on the terminal. */
int main(int argc, char *argv[])
    {
    if (!hasDisplay())
        {
        QCoreApplication app(argc, argv);
        QCoreApplication::setApplicationName("fg-configurator");
        QCoreApplication::setApplicationVersion(FG_VERSION);
        QCommandLineParser parser;
        parseCommandLine(parser, app);
        return dialog(parser.isSet("verbose"));
        }
    QApplication app(argc, argv);
    QApplication::setApplicationName("fg-configurator");
    QApplication::setApplicationVersion(FG_VERSION);
    QCommandLineParser parser;
    parseCommandLine(parser, app);
    MainWindow w;
    return app.exec();
    }
